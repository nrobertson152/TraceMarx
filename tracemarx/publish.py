"""Publish TraceMarx outputs into RevisionWorx, next to the schematic they were made from.

The wiring book (PDF) becomes document ``<schematic number>-WL`` and the labels (PDF) ``<schematic number>-LBL``
in the schematic's own RevisionWorx project. Publishing again adds a new revision of the same documents. Every
check-in message names the exact source revision and its SHA-256, so each printed list can be traced back.

Refused when the schematic file differs from its latest revision (someone is editing it, or it changed outside
RevisionWorx): outputs must come from a recorded revision. ``allow_unrecorded`` overrides this on request."""
from __future__ import annotations

import tempfile
from pathlib import Path

from . import APP_NAME, VERSION
from .harness import Harness


class PublishRefused(Exception):
    pass


def plan(rwx, h: Harness, source_path: str, project: str | None = None) -> dict:
    """What publishing would do, without doing it: numbers, titles, project and the source revision."""
    st = rwx.status(source_path)
    doc = st.get("document") if st.get("controlled") else None
    if doc is None and not project:
        raise PublishRefused("This schematic is not in RevisionWorx. Add it to a project first (or choose the "
                             "project to put the outputs in).")
    base = (doc or {}).get("number") or h.source.drawing_number or Path(source_path).stem
    latest = (doc or {}).get("latest") or {}
    source = f"{base} rev {latest['label']} ({latest['state_name']})" if latest else h.source.name
    return {"status": st, "project": project or doc["project"]["id"], "base": base, "source": source,
            "file_state": (st.get("file") or {}).get("state"),
            "documents": [{"number": f"{base}-WL", "title": f"Wiring book for {base}", "kind": "book"},
                          {"number": f"{base}-LBL", "title": f"Labels for {base}", "kind": "labels"}],
            "message": f"Generated by {APP_NAME} {VERSION} from {source}, SHA-256 {h.source.sha256[:16]}"}


def publish(rwx, h: Harness, source_path: str, project: str | None = None, paper: str = "A4",
            layout: str | None = None, keep_in: Path | None = None, allow_unrecorded: bool = False,
            label_options=None) -> list[dict]:
    from . import labels, reports
    p = plan(rwx, h, source_path, project)
    if p["status"].get("controlled") and p["file_state"] != "unchanged" and not allow_unrecorded:
        raise PublishRefused(f"The schematic file differs from {p['source']} (state: {p['file_state']}). Check it "
                             "in first, so the wiring book and labels come from a recorded revision.")
    folder = Path(keep_in) if keep_in else Path(tempfile.mkdtemp(prefix="tracemarx-publish-"))
    folder.mkdir(parents=True, exist_ok=True)
    rwx_label = p["source"] if p["status"].get("controlled") else ""
    results = []
    for d in p["documents"]:
        f = folder / f"{d['number']}.pdf"
        if d["kind"] == "book":
            f.write_bytes(reports.wiring_book(h, paper, rwx_label))
        else:
            labs = labels.make_labels(h, label_options or labels.LabelOptions())
            f.write_bytes(labels.to_pdf(labs, labels.LAYOUTS[layout or labels.DEFAULT_LAYOUT],
                                        title=f"{h.source.title} - labels"))
        results.append(rwx.publish(str(f), project=p["project"], number=d["number"], title=d["title"],
                                   message=p["message"]))
    return results
